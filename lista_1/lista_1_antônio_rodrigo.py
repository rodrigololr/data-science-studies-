  X = df.drop(columns=["Class"])
  y = df["Class"]

  #usando o método ANOVA(f_classif) todas as colunas
  selector = SelectKBest(score_func=f_classif, k='all')
  selector.fit(X, y)

  #extração de pontuações de assosiação
  scores = selector.scores_

  # dataframe ranking
  ranking_df = pd.DataFrame({'Variável': X.columns, 'Score': scores})
  ranking_df = ranking_df.sort_values(by='Score', ascending=False).reset_index(drop=True)

  print(ranking_df.head())

  #criando um grafico com os 15 que mais tem associação
