def comparar_esquemas_preprocessamento(df, test_size=0.2, random_state=42):
    X = df.drop(columns=['Class'])
    y = df['Class']

    # split único evitar leakage e manter comparação justa
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=random_state, stratify=y
    )

    # seletores automáticos por tipo de dado
    num_selector = make_column_selector(dtype_include=np.number)
    cat_selector = make_column_selector(dtype_include=object)

    # esquema A: imputação por média + StandardScaler
    pipe_num_std = Pipeline([
        ('imputer', SimpleImputer(strategy='mean')),
        ('scaler', StandardScaler())
    ])
    preprocessor_std = ColumnTransformer([
        ('num', pipe_num_std, num_selector),
        ('cat', OneHotEncoder(handle_unknown='ignore'), cat_selector)
    ])

    # esquema B: imputação por mediana + RobustScaler
    pipe_num_rob = Pipeline([
        ('imputer', SimpleImputer(strategy='median')),
        ('scaler', RobustScaler())
    ])
    preprocessor_rob = ColumnTransformer([
        ('num', pipe_num_rob, num_selector),
        ('cat', OneHotEncoder(handle_unknown='ignore'), cat_selector)
    ])

    # ajuste APENAS no treino (sem vazamento)
    X_train_std = preprocessor_std.fit_transform(X_train)
    X_test_std = preprocessor_std.transform(X_test)

