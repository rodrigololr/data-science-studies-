def detectar_outliers_extremos(df):
    df_num = df.select_dtypes(include=['number']).drop(columns=['Class'], errors='ignore')

    Q1 = df_num.quantile(0.25)
    Q3 = df_num.quantile(0.75)
    IQR = Q3 - Q1

    limite_inferior = Q1 - (3 * IQR)
    limite_superior = Q3 + (3 * IQR)

    valor_outlier = (df_num < limite_inferior) | (df_num > limite_superior)

    total_outliers = valor_outlier.sum()

    return total_outliers[total_outliers > 0]

